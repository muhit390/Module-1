public class Variables {

    public static void main(String[] args) {
        int dogCount = 94;
        int catCount = 112;
        int petCount = dogCount * catCount;
        System.out.println(petCount); // 206

        int tacos = 12;

        System.out.println(tacos);

        tacos = 29;

        System.out.println(tacos);
    }

}
